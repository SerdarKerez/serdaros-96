/* Generates supabase/seed.sql from the built-in content (lib/site-data/defaults.ts).
   Run: npm run seed:sql */
import { writeFileSync } from "node:fs";
import { DEFAULT_SITE_DATA } from "../lib/site-data/defaults";
import { SITE_KEYS } from "../lib/site-data/types";

const TAG = "$serdaros_seed$";
const parts = SITE_KEYS.map((key) => {
  const json = JSON.stringify(DEFAULT_SITE_DATA[key]);
  if (json.includes(TAG)) throw new Error("seed delimiter found in data");
  return `insert into public.site_content (key, data) values ('${key}', ${TAG}${json}${TAG}::jsonb)\n  on conflict (key) do nothing;`;
});
const sql = `-- SerdarOS 96 — seed: current site content. Generated by scripts/generate-seed.ts; do not edit by hand.
-- Run after schema.sql. Existing rows are kept (on conflict do nothing).
${parts.join("\n\n")}
`;
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log("supabase/seed.sql written,", (sql.length / 1024).toFixed(1), "KB");
